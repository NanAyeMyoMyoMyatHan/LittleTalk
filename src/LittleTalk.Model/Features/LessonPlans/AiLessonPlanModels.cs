namespace LittleTalk.Model.Features.LessonPlans;

/// <summary>
/// Request contract for AI-powered English speaking lesson plan generation.
/// </summary>
public class GenerateAiLessonPlanRequestModel
{
    public string Topic { get; set; } = string.Empty;
    public string? TargetAgeGroup { get; set; }
    public int LearningLevelId { get; set; }
    public int DurationMinutes { get; set; } = 30;
    public int? CourseId { get; set; }
    public string? SpecificFocusNotes { get; set; }
}

/// <summary>
/// Structured response model containing age-appropriate speaking lesson plan content generated by AI.
/// </summary>
public class GenerateAiLessonPlanResponseModel
{
    public string Title { get; set; } = string.Empty;
    public string Topic { get; set; } = string.Empty;
    public string AgeGroup { get; set; } = string.Empty;
    public int LearningLevelId { get; set; }
    public int DurationMinutes { get; set; }
    public string LearningObjectives { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;
    public List<string> SentencePatterns { get; set; } = new();
    public List<string> TeachingMaterials { get; set; } = new();
    public string AssessmentNotes { get; set; } = string.Empty;
    public List<AiLessonStepDto> Steps { get; set; } = new();
    public List<AiLessonVocabularyDto> Vocabulary { get; set; } = new();
}

/// <summary>
/// Structured pedagogical step produced by the AI generator.
/// </summary>
public class AiLessonStepDto
{
    public string StepName { get; set; } = string.Empty;
    public int DurationMinutes { get; set; }
    public int? TeachingMethodId { get; set; }
    public string? TeachingMethodName { get; set; }
    public string Instructions { get; set; } = string.Empty;
    public string? TeacherScript { get; set; }
    public string? ExpectedStudentResponse { get; set; }
    public int SortOrder { get; set; }
}

/// <summary>
/// Structured vocabulary item with pronunciation and kid-friendly example sentence.
/// </summary>
public class AiLessonVocabularyDto
{
    public string Word { get; set; } = string.Empty;
    public string Meaning { get; set; } = string.Empty;
    public string? Pronunciation { get; set; }
    public string ExampleSentence { get; set; } = string.Empty;
    public int SortOrder { get; set; }
}
